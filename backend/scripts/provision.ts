import fs from "node:fs";
import path from "node:path";
import { DeviceSecrets, IMEI_PATTERN } from "../src/crypto/device.ts";

// Secrets of a tracker given its IMEI:
// - DEVICE_KEY for firmware/secrets.h
// - the pairing code and the QR content (CT1:<IMEI>:<CODE>) for the label: the owner
//   scans it in the app to add the tracker to the account
// With --label <file.svg> it also writes the label to print.
// Usage: npm run provision -- <IMEI> [--label label.svg]

const args = process.argv.slice(2);
const imei = args[0] ?? "";
const labelIndex = args.indexOf("--label");
const labelFile = labelIndex >= 0 ? args[labelIndex + 1] : undefined;

if (!IMEI_PATTERN.test(imei) || (labelIndex >= 0 && !labelFile)) {
	console.error("Usage: npm run provision -- <IMEI (15 digits)> [--label label.svg]");
	process.exit(1);
}
const masterKey = process.env.CRYPTO_MASTER_KEY ?? "";
if (masterKey.length < 32) {
	console.error("CRYPTO_MASTER_KEY is not set (min 32 characters)");
	process.exit(1);
}

const secrets = new DeviceSecrets(masterKey);
const code = secrets.pairingCode(imei);
const qr = `CT1:${imei}:${code.replace("-", "")}`;

console.log(`IMEI:          ${imei}`);
console.log(`Pairing code:  ${code}`);
console.log(`QR content:    ${qr}`);
console.log();
console.log("firmware/secrets.h:");
console.log(`#define DEVICE_KEY "${secrets.deviceKey(imei).toString("hex")}"`);

if (labelFile) {
	// Text label: the app reads the QR, generated by any label printer / qrencode:
	//   qrencode -t SVG -o qr.svg "CT1:..."
	const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="320" height="120" viewBox="0 0 320 120">
	<rect width="320" height="120" fill="#fff" stroke="#000"/>
	<text x="16" y="36" font-family="monospace" font-size="16">Car Tracking</text>
	<text x="16" y="66" font-family="monospace" font-size="14">IMEI ${imei}</text>
	<text x="16" y="98" font-family="monospace" font-size="22" font-weight="bold">${code}</text>
</svg>
`;
	fs.writeFileSync(path.resolve(labelFile), svg);
	console.log(`\nLabel written to ${labelFile}. QR: qrencode -t SVG -o qr.svg "${qr}"`);
}
