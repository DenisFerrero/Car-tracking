import fs from "node:fs";
import path from "node:path";
import tls from "node:tls";
import { X509Certificate } from "node:crypto";

// Generates firmware/certificates.h with the root CAs accepted by the tracker for the TLS
// connection to the server: Let's Encrypt (Traefik ACME), Google Trust Services and SSL.com
// (Cloudflare edge). Taken from the Mozilla store bundled in Node.
// Usage: npm run ca-bundle

const ROOTS = [
	"ISRG Root X1",
	"ISRG Root X2",
	"GTS Root R1",
	"GTS Root R4",
	"SSL.com TLS RSA Root CA 2022",
	"SSL.com TLS ECC Root CA 2022"
];

const TARGET = path.join(import.meta.dirname, "../../firmware/certificates.h");

const found = new Map<string, string>();
for (const pem of tls.rootCertificates) {
	const cn = new X509Certificate(pem).subject.split("\n").find(line => line.startsWith("CN="));
	const name = cn?.slice(3);
	if (name && ROOTS.includes(name)) found.set(name, pem.trim());
}

const missing = ROOTS.filter(name => !found.has(name));
if (missing.length > 0) {
	console.error("Root CAs not found in the Node store:", missing.join(", "));
	process.exit(1);
}

const body = ROOTS.map(name => {
	const pem = found.get(name)!;
	const lines = pem.split("\n").map(line => `"${line}\n"`).join("\n");
	return `// ${name}, valid until ${new X509Certificate(pem).validTo}\n${lines}`;
}).join("\n");

fs.writeFileSync(TARGET, `#ifndef CERTIFICATES_H
#define CERTIFICATES_H

// Root CAs accepted for the TLS connection to the server: Let's Encrypt (Traefik), Google
// Trust Services and SSL.com (Cloudflare edge certificates).
// Generated by backend/scripts/ca-bundle.ts (npm run ca-bundle), don't edit by hand.

static const char SERVER_CA_BUNDLE[] =
${body};

#endif
`);
console.log(`Written ${TARGET}: ${ROOTS.length} root CAs`);
