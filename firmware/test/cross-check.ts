/**
 * Cross test between the firmware encoder (firmware/protocol.cpp) and the backend
 * decoder (backend/src/protocol/protocol.ts).
 *
 * Usage (Node 24): node firmware/test/cross-check.ts <path of the compiled protocol_test>
 */
import assert from "node:assert";
import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import { DeviceSecrets } from "../../backend/src/crypto/device.ts";
import * as protocol from "../../backend/src/protocol/protocol.ts";
import type { Point } from "../../backend/src/protocol/protocol.ts";

const IMEI = "863820040182648";
const key = new DeviceSecrets("cross-check-master-key-at-least-32-chars").deviceKey(IMEI);
const ack = protocol.encodeAck(key, 300, 77, 1763625700);
const command = protocol.encodeCommand(key, 1763625750, 1763625750, [
	{ id: protocol.COMMAND.LIVE, seconds: 300 },
	{ id: protocol.COMMAND.ANTITHEFT, seconds: 86400 },
	{ id: protocol.COMMAND.LOCATE }
]);

const sha256 = crypto.createHash("sha256").update("image").digest();
const offer = protocol.encodeFirmwareOffer(key, 1763625760, 1763625760, { size: 1234567, sha256, version: "2.3.0" });

const output = execFileSync(process.argv[2]!, [key.toString("hex"), ack.toString("hex"), command.toString("hex"), offer.toString("hex")]).toString();
const lines = output.trim().split(/\r?\n/).map(text => text.split(" "));
const line = (name: string) => lines.find(item => item[0] === name)!;

// HELLO
const hello = protocol.parseFrame(Buffer.from(lines[0]![1]!, "hex"));
assert.strictEqual(hello.imei, IMEI);
assert.deepStrictEqual(protocol.decodeHello(protocol.decryptFrame(hello, key)!), {
	manufacturer: "SIMCOM INCORPORATED", model: "A7670E-LASE", revision: "A7670M7_V1.11.1", firmware: "2.0.0"
});

// TELEMETRY, the same points generated by protocol_test.cpp
const points: Point[] = [];
const frames = lines.filter(item => item[0] === "telemetry");
for (const [, hex] of frames) {
	const buffer = Buffer.from(hex!, "hex");
	assert.ok(buffer.length <= 120, "frame larger than the capacity");
	const frame = protocol.parseFrame(buffer);
	assert.strictEqual(frame.deviceId, 300);
	const plaintext = protocol.decryptFrame(frame, key);
	assert.ok(plaintext, "telemetry authentication failed");
	points.push(...protocol.decodeTelemetry(plaintext, frame.timestamp));
}
assert.strictEqual(points.length, 40);

points.forEach((point, i) => {
	let full = true, partial = true;
	if (i % 9 === 4) full = false;
	if (i % 11 === 6) partial = false;

	assert.strictEqual(point.time.getTime() / 1000, 1763625600 + i * 5 + (i > 20 ? 60 : 0));
	assert.strictEqual(Math.round(point.lat * 1e5), 4546421 + i * 41 - (i % 7) * 13);
	assert.strictEqual(Math.round(point.lon * 1e5), -7318003 - i * 52 + (i % 5) * 9);
	assert.strictEqual(point.status, i % 4);
	assert.strictEqual(point.altitude, partial ? -12 + i : null);
	assert.strictEqual(point.speed, partial ? i * 6 : null);
	assert.strictEqual(point.pressure, full ? (10132 - i * 3) / 10 : null);
	assert.strictEqual(point.temperature, full ? (-55 + i * 4) / 10 : null);
	assert.strictEqual(point.satellites, i % 3 === 0 ? 4 + i % 9 : null);
	assert.strictEqual(point.signal, i % 4 === 1 ? -(60 + i) : null);
	assert.strictEqual(point.voltage, i % 5 === 2 ? (1180 + i * 7) / 100 : null);
	assert.strictEqual(point.events, i % 13 === 0 ? protocol.EVENT.MOTION | protocol.EVENT.TILT : 0);
	assert.strictEqual(point.stale, i % 8 === 7);
	assert.deepStrictEqual(point.cell, i % 8 === 7
		? { mcc: 222, mnc: i % 3 === 0 ? 1 : 88, area: 0x5a1b + i, id: 26834437 + i * 1000 }
		: null);
});

// ACK
assert.deepStrictEqual(line("ack"), ["ack", "ok", "300"]);
assert.deepStrictEqual(line("tampered"), ["tampered", "fail"]);

// COMMAND decoded by the firmware, its result decoded by the backend
assert.deepStrictEqual(line("command"),
	["command", "1763625750", "1763625750", "0", "1:300", "2:86400", "3:0"]);
assert.deepStrictEqual(line("command-as-ack"), ["command-as-ack", "fail"]);
const result = protocol.parseFrame(Buffer.from(line("result")[1]!, "hex"));
assert.strictEqual(result.type, protocol.TYPE.COMMAND_RESULT);
assert.strictEqual(result.deviceId, 300);
assert.deepStrictEqual(protocol.decodeCommandResult(protocol.decryptFrame(result, key)!), {
	counter: 1763625750, result: protocol.RESULT.EXPIRED
});

// Firmware update: offer decoded by the firmware, plain frames decoded by the backend
assert.deepStrictEqual(line("offer"), ["offer", "1763625760", "1234567", "2.3.0", sha256.toString("hex")]);
assert.deepStrictEqual(line("offer-as-command"), ["offer-as-command", "fail"]);
const request = Buffer.from(line("fw-request")[1]!, "hex");
assert.strictEqual(protocol.plainType(request), protocol.TYPE.FW_REQUEST);
assert.deepStrictEqual(protocol.decodeFirmwareRequest(request), { offset: 70000, length: 32768 });
const fwResult = Buffer.from(line("fw-result")[1]!, "hex");
assert.strictEqual(protocol.plainType(fwResult), protocol.TYPE.FW_RESULT);
assert.strictEqual(protocol.decodeFirmwareResult(fwResult), protocol.FW_STATUS.BAD_HASH);

// UPDATE_CHECK: no payload; EXTRA: the JSON as it is, too big or empty: not built
const check = protocol.parseFrame(Buffer.from(line("update-check")[1]!, "hex"));
assert.deepStrictEqual([check.type, check.deviceId, check.counter, check.timestamp], [protocol.TYPE.UPDATE_CHECK, 300, 2000, 1763625700]);
assert.strictEqual(protocol.decryptFrame(check, key)!.length, 0);
const extra = protocol.parseFrame(Buffer.from(line("extra")[1]!, "hex"));
assert.deepStrictEqual([extra.type, extra.deviceId, extra.timestamp], [protocol.TYPE.EXTRA, 300, 1763625710]);
assert.deepStrictEqual(protocol.decodeExtra(protocol.decryptFrame(extra, key)!), { rpm: 820, coolant: 88.5, dtc: ["P0420"] });
assert.deepStrictEqual(line("extra-limits"), ["extra-limits", "0", "0"]);

// Owner beacon: the rolling code of the firmware matches a reference HMAC-SHA256
const beacon = Buffer.from(line("beacon")[1]!, "hex");
const message = Buffer.concat([Buffer.from("CTB1"), Buffer.from([7]), Buffer.alloc(4)]);
message.writeUInt32LE(58787520, 5);
const code = crypto.createHmac("sha256", key).update(message).digest().subarray(0, 8);
const expected = Buffer.concat([Buffer.from([0xff, 0xff, 0x43, 0x54, 1, 7]), message.subarray(5), code]);
assert.strictEqual(beacon.toString("hex"), expected.toString("hex"));
assert.deepStrictEqual(line("beacon-check"), ["beacon-check", "ok", "fail"]);

const bytes = frames.reduce((total, [, hex]) => total + hex!.length / 2, 0);
console.log(`OK: hello ${lines[0]![1]!.length / 2} B, 40 points in ${frames.length} frames (${bytes} B, ${(bytes / 40).toFixed(1)} B/point), ack, command (${command.length} B), result, firmware offer, update check, extra data and beacon verified`);
